// ✅ FUNCIÓN UTILITARIA: Buscar emojis por categoría
export function buscarEmojisPorCategoria(categoria) {
  return BBDD_LUMAI.filter(item => item.categoria === categoria);
}

// ✅ FUNCIÓN UTILITARIA: Buscar emoji por palabra
export function buscarEmojiPorPalabra(palabra) {
  return BBDD_LUMAI.find(item => item.palabra === palabra.toUpperCase());
}

// ✅ FUNCIÓN UTILITARIA: Obtener todas las categorías
export function obtenerCategorias() {
  const categorias = [...new Set(BBDD_LUMAI.map(item => item.categoria))];
  return categorias.sort();
}

// ✅ FUNCIÓN UTILITARIA: Obtener estadísticas
export function obtenerEstadisticas() {
  const stats = {
    totalEmojis: BBDD_LUMAI.length,
    totalCategorias: 0,
    emojisPorCategoria: {}
  };
  
  const categorias = obtenerCategorias();
  stats.totalCategorias = categorias.length;
  
  categorias.forEach(categoria => {
    stats.emojisPorCategoria[categoria] = buscarEmojisPorCategoria(categoria).length;
  });
  
  return stats;
}

